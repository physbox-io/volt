// ---------------------------------------------------------------------------
// Gerber (RS-274X) + Excellon export for real PCB fabrication.
//
// Volt's own CAM pipeline (pcbExporter.ts) ends at G-code, streamed straight
// to a CNC over WebSerial. That's a mill-it-yourself path; most boards go to
// a fab house instead (JLCPCB, PCBWay, OSHPark, ...), which read the same two
// ancient, boring formats every PCB tool speaks: RS-274X for copper/outline
// layers, and Excellon for drill hits.
//
// Reuses `PcbLayoutResult.copperByNet` (populated in pcbExporter.ts as a side
// effect of the flood-fill stage that already runs for the SVG preview and the
// isolation toolpaths) rather than re-deriving copper from traces/pads here —
// two independent flood-fill implementations would drift, and the whole point
// of a Gerber export is that it matches what the mill would actually cut.
// ---------------------------------------------------------------------------

import JSZip from 'jszip';
import type { PcbLayoutResult, DrillPoint, BoardCutout, PlacedPad } from './pcbExporter';
import { polyArea, pointInPolys, type Poly } from './pcbGeometry';

/** Gerber fixed-point format: 3 integer + 4 fractional digits (0.1um steps). */
const COORD_SCALE = 1e4;
/** Standard fab-house solder mask expansion per side, in mm. */
const SOLDER_MASK_EXPANSION_MM = 0.075;

function formatCoord(mm: number): string {
  return String(Math.round(mm * COORD_SCALE));
}

/** Excellon wants zero-padded fixed-width coordinates, no decimal point. */
function formatExcellonCoord(mm: number): string {
  const negative = mm < 0;
  const units = Math.round(Math.abs(mm) * COORD_SCALE);
  return (negative ? '-' : '') + String(units).padStart(7, '0');
}

function gerberHeader(layerFunction: string): string {
  return (
    '%FSLAX34Y34*%\n' +
    '%MOMM*%\n' +
    '%LPD*%\n' +
    'G01*\n' +
    'G04 Generated by PhysBox: Volt*\n' +
    '%TF.GenerationSoftware,PhysBox,Volt,1.0*%\n' +
    `%TF.FileFunction,${layerFunction}*%\n`
  );
}

function appendRegion(lines: string[], ring: Poly): void {
  if (ring.length < 3) return;
  lines.push('G36*');
  lines.push(`X${formatCoord(ring[0].x)}Y${formatCoord(ring[0].y)}D02*`);
  for (let i = 1; i < ring.length; i++) {
    lines.push(`X${formatCoord(ring[i].x)}Y${formatCoord(ring[i].y)}D01*`);
  }
  lines.push(`X${formatCoord(ring[0].x)}Y${formatCoord(ring[0].y)}D01*`);
  lines.push('G37*');
}

/**
 * Splices interior hole rings into their enclosing outer ring via RS-274X
 * keyhole cut-ins so the entire polygon with holes renders as one valid
 * `%LPD*%` `G36*..G37*` region without painting holes as solid copper.
 */
function mergeHolesIntoOuter(outer: Poly, holes: Poly[]): Poly {
  let merged = outer.slice();
  // Process holes right-to-left (largest max-X first) so cut-ins are less
  // likely to cross each other.
  const ordered = holes
    .filter(h => h.length >= 3)
    .map(h => ({ h, maxX: Math.max(...h.map(p => p.x)) }))
    .sort((a, b) => b.maxX - a.maxX);

  for (const { h } of ordered) {
    let bestOi = 0;
    let bestHi = 0;
    let bestD2 = Infinity;
    for (let oi = 0; oi < merged.length; oi++) {
      const op = merged[oi];
      for (let hi = 0; hi < h.length; hi++) {
        const hp = h[hi];
        const d2 = (op.x - hp.x) ** 2 + (op.y - hp.y) ** 2;
        if (d2 < bestD2) {
          bestD2 = d2;
          bestOi = oi;
          bestHi = hi;
        }
      }
    }
    const holeRotated = [...h.slice(bestHi), ...h.slice(0, bestHi)];
    merged = [
      ...merged.slice(0, bestOi + 1),
      ...holeRotated,
      holeRotated[0],
      merged[bestOi],
      ...merged.slice(bestOi + 1),
    ];
  }
  return merged;
}

function generateCopperLayer(
  copperByNet: Map<string, Poly[]>,
  layerFunction: string,
  mx: (x: number) => number
): string {
  const lines: string[] = [gerberHeader(layerFunction), '%ADD10C,0.1*%', 'D10*'];
  const mirrorPoly = (ring: Poly): Poly =>
    ring.map(p => ({ x: mx(p.x), y: p.y })).reverse();
  const isMirrored = mx(0) !== 0 || mx(1) !== 1;

  for (const rawPolys of copperByNet.values()) {
    const polys = isMirrored ? rawPolys.map(mirrorPoly) : rawPolys;
    const outers: Poly[] = [];
    const holes: Poly[] = [];
    for (const ring of polys) {
      if (ring.length < 3) continue;
      if (polyArea(ring) >= 0) outers.push(ring);
      else holes.push(ring);
    }

    if (holes.length === 0) {
      for (const ring of outers) appendRegion(lines, ring);
      continue;
    }

    // Assign each hole to its smallest enclosing outer ring.
    const holesByOuter = new Map<number, Poly[]>();
    for (const hole of holes) {
      let bestIdx = -1;
      let bestArea = Infinity;
      for (let i = 0; i < outers.length; i++) {
        const a = polyArea(outers[i]);
        if (a < bestArea && pointInPolys([outers[i]], hole[0])) {
          bestArea = a;
          bestIdx = i;
        }
      }
      if (bestIdx >= 0) {
        const list = holesByOuter.get(bestIdx) ?? [];
        list.push(hole);
        holesByOuter.set(bestIdx, list);
      }
    }

    for (let i = 0; i < outers.length; i++) {
      const assigned = holesByOuter.get(i);
      appendRegion(lines, assigned ? mergeHolesIntoOuter(outers[i], assigned) : outers[i]);
    }
  }
  lines.push('M02*');
  return lines.join('\n') + '\n';
}

function generateSolderMaskLayer(
  pads: PlacedPad[],
  layerFunction: string,
  mx: (x: number) => number,
  includeSmd: boolean
): string {
  const lines: string[] = [gerberHeader(layerFunction), '%ADD10C,0.1*%', 'D10*'];
  for (const pad of pads) {
    const isTht = (pad.spec.drillDiameter ?? 0) > 0;
    if (!isTht && !includeSmd) continue;
    const cx = mx(pad.x);
    const cy = pad.y;
    const w = pad.spec.padWidth + SOLDER_MASK_EXPANSION_MM * 2;
    const h = pad.spec.padHeight + SOLDER_MASK_EXPANSION_MM * 2;
    if (pad.spec.shape === 'circle') {
      const r = Math.max(w, h) / 2;
      const steps = 20;
      const ring: Poly = [];
      for (let i = 0; i < steps; i++) {
        const a = (i / steps) * Math.PI * 2;
        ring.push({ x: cx + r * Math.cos(a), y: cy + r * Math.sin(a) });
      }
      appendRegion(lines, ring);
    } else {
      const hw = w / 2;
      const hh = h / 2;
      appendRegion(lines, [
        { x: cx - hw, y: cy - hh },
        { x: cx + hw, y: cy - hh },
        { x: cx + hw, y: cy + hh },
        { x: cx - hw, y: cy + hh },
      ]);
    }
  }
  lines.push('M02*');
  return lines.join('\n') + '\n';
}

function generateOutlineLayer(
  boardWidthMm: number,
  boardHeightMm: number,
  boardOriginMm: number,
  cutouts: BoardCutout[],
  mx: (x: number) => number
): string {
  const lines: string[] = [gerberHeader('Profile,NP'), '%ADD11C,0.1*%', 'D11*'];

  const strokeClosedPath = (pts: { x: number; y: number }[]) => {
    if (pts.length < 2) return;
    lines.push(`X${formatCoord(pts[0].x)}Y${formatCoord(pts[0].y)}D02*`);
    for (let i = 1; i < pts.length; i++) {
      lines.push(`X${formatCoord(pts[i].x)}Y${formatCoord(pts[i].y)}D01*`);
    }
    lines.push(`X${formatCoord(pts[0].x)}Y${formatCoord(pts[0].y)}D01*`);
  };

  const x0 = boardOriginMm;
  const y0 = boardOriginMm;
  strokeClosedPath([
    { x: x0, y: y0 },
    { x: x0 + boardWidthMm, y: y0 },
    { x: x0 + boardWidthMm, y: y0 + boardHeightMm },
    { x: x0, y: y0 + boardHeightMm },
  ]);

  // Interior cutouts (slots and circular holes) as closed contours on Edge_Cuts.
  for (const cutout of cutouts) {
    const cx = mx(cutout.x);
    if (cutout.shape === 'circle') {
      const r = Math.max(cutout.widthMm, cutout.heightMm) / 2;
      if (r <= 0) continue;
      const steps = 36;
      const pts: { x: number; y: number }[] = [];
      for (let i = 0; i < steps; i++) {
        const a = (i / steps) * Math.PI * 2;
        pts.push({ x: cx + r * Math.cos(a), y: cutout.y + r * Math.sin(a) });
      }
      strokeClosedPath(pts);
      continue;
    }
    const hw = cutout.widthMm / 2;
    const hh = cutout.heightMm / 2;
    strokeClosedPath([
      { x: cx - hw, y: cutout.y - hh },
      { x: cx + hw, y: cutout.y - hh },
      { x: cx + hw, y: cutout.y + hh },
      { x: cx - hw, y: cutout.y + hh },
    ]);
  }

  lines.push('M02*');
  return lines.join('\n') + '\n';
}

function generateExcellonDrill(
  drills: DrillPoint[],
  mx: (x: number) => number
): { text: string; drillCount: number } {
  // One tool per distinct diameter, rounded to the micron.
  const toolDiameterByKey = new Map<number, number>();
  for (const d of drills) {
    const key = Math.round(d.diameter * 1000);
    toolDiameterByKey.set(key, d.diameter);
  }
  const sortedKeys = [...toolDiameterByKey.keys()].sort((a, b) => a - b);
  const toolNumberByKey = new Map<number, number>();
  sortedKeys.forEach((key, i) => toolNumberByKey.set(key, i + 1));

  const lines: string[] = ['M48', ';FILE_FORMAT=3:4', 'METRIC,LZ'];
  for (const key of sortedKeys) {
    const toolNum = String(toolNumberByKey.get(key)).padStart(2, '0');
    lines.push(`T${toolNum}C${toolDiameterByKey.get(key)!.toFixed(3)}`);
  }
  lines.push('%', 'G90', 'G05');

  let drillCount = 0;
  for (const key of sortedKeys) {
    const toolNum = String(toolNumberByKey.get(key)).padStart(2, '0');
    lines.push(`T${toolNum}`);
    for (const d of drills) {
      if (Math.round(d.diameter * 1000) !== key) continue;
      lines.push(`X${formatExcellonCoord(mx(d.x))}Y${formatExcellonCoord(d.y)}`);
      drillCount++;
    }
  }
  lines.push('M30');
  return { text: lines.join('\n') + '\n', drillCount };
}

export interface GerberExportFiles {
  [filename: string]: string;
}

/**
 * Renders a routed board to a fab-house-ready file set. Two-layer boards get
 * both copper and solder-mask layers; single-layer boards are un-mirrored back
 * to top-view orientation so fab houses produce the right handedness.
 */
export function generateGerberFiles(result: PcbLayoutResult): GerberExportFiles {
  const files: GerberExportFiles = {};
  const xMid = result.boardOriginMm + result.boardWidthMm / 2;
  const mx = result.mirrored ? (x: number) => 2 * xMid - x : (x: number) => x;

  files['board-F_Cu.gtl'] = generateCopperLayer(result.copperByNet, 'Copper,L1,Top', mx);
  files['board-F_Mask.gts'] = generateSolderMaskLayer(result.pads, 'Soldermask,Top', mx, true);
  if (result.layers === 2 && result.bottomCopperByNet) {
    files['board-B_Cu.gbl'] = generateCopperLayer(result.bottomCopperByNet, 'Copper,L2,Bot', mx);
    files['board-B_Mask.gbs'] = generateSolderMaskLayer(result.pads, 'Soldermask,Bot', mx, false);
  }
  files['board-Edge_Cuts.gko'] = generateOutlineLayer(
    result.boardWidthMm,
    result.boardHeightMm,
    result.boardOriginMm,
    result.cutouts,
    mx
  );
  // Exclude CNC spoilboard registration pins (located outside the board outline).
  const drill = generateExcellonDrill(
    result.drills.filter(d => d.diameter > 0 && !d.isRegistration),
    mx
  );
  files['board.drl'] = drill.text;

  return files;
}

/** Bundles the Gerber/Excellon file set into a single downloadable zip. */
export async function generateGerberZip(result: PcbLayoutResult): Promise<Blob> {
  const files = generateGerberFiles(result);
  const zip = new JSZip();
  for (const [name, contents] of Object.entries(files)) {
    zip.file(name, contents);
  }
  return zip.generateAsync({ type: 'blob' });
}
